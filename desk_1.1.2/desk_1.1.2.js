// Запитуємо пароль у користувача
let password = prompt("Введіть пароль:");

// Перевіряємо довжину пароля
if (password.length < 6) {
    alert("Пароль має бути не менше 6 символів!");
} 
// Перевіряємо, чи містить пароль пробіли
else if (password.includes(" ")) {
    alert("Пароль не повинен містити пробіли!");
} 
// Якщо всі умови виконані, приймаємо пароль
else {
    alert("Пароль прийнято!");
}