// Генеруємо випадкове число від 0 до 100
let secretNumber = Math.floor(Math.random() * 101);
let attempts = 0; // Лічильник спроб
let guess; // Введене користувачем число

// Запускаємо цикл, поки користувач не вгадає число
while (true) {
    // Запитуємо у користувача число
    guess = prompt("Вгадайте число від 0 до 100:");
    
    // Перетворюємо введене значення у число
    guess = parseInt(guess);
    attempts++; // Збільшуємо лічильник спроб

    // Перевіряємо, чи введене значення є числом
    if (isNaN(guess)) {
        alert("Будь ласка, введіть число!");
        continue; // Продовжуємо запит
    }

    // Перевіряємо введене число
    if (guess > secretNumber) {
        alert("Ваше число більше.");
    } else if (guess < secretNumber) {
        alert("Ваше число менше.");
    } else {
        alert(`Вітаємо, ви вгадали число за ${attempts} спроб!`);
        break; // Вихід з циклу, гра завершена
    }
}
